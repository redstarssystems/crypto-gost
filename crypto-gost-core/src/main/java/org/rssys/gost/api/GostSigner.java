package org.rssys.gost.api;

import org.rssys.gost.signature.ECParameters;
import org.rssys.gost.signature.NonceMode;
import org.rssys.gost.signature.PrivateKeyParameters;
import org.rssys.gost.signature.PublicKeyParameters;

/**
 * Абстракция подписанта ГОСТ Р 34.10-2012 для сборки X.509-объектов (сертификаты, CRL, CSR).
 *
 * <p>Отделяет операцию подписи от материала закрытого ключа: реализация может подписывать
 * внутри аппаратного модуля (HSM/PKCS#11/внешний CSP), не извлекая закрытый ключ в
 * память JVM. Билдеры пакета {@code pkix.cert} вычисляют хэш TBS-структуры и передают его
 * подписанту через {@link #signHash(byte[])}; наружу возвращается только готовая подпись.
 *
 * <p>Для сценариев, где HSM не нужен (тесты, некритичные операции), используйте
 * {@link #of(PrivateKeyParameters)} — тонкий мост поверх ключа в памяти.
 *
 * <h3>Контракт формата подписи</h3>
 * {@link #signHash(byte[])} обязан вернуть подпись в X.509-формате {@code s ∥ r} big-endian
 * (как {@code SignatureCodec.encode}): каждая компонента {@code ceil(n.bitLength()/8)} байт,
 * итог 64 байта для 256-битных кривых, 128 для 512-битных.
 *
 * <h3>Контракт нонса</h3>
 * Нонс k — секретный эфемерный ключ, его повтор при разных хэшах раскрывает закрытый ключ.
 * Реализация по умолчанию ({@link #of(PrivateKeyParameters)}) вырабатывает нонс гибридно: во
 * вход подмешиваются свежие случайные байты, подпись одного хэша каждый раз другая; воспроизводимую
 * подпись даёт {@link #of(PrivateKeyParameters, NonceMode)} с {@link NonceMode#DETERMINISTIC}.
 * Детерминированный нонс обязан зависеть только от {@code (d, e)} и параметров кривой, где
 * {@code e} — число из уравнения подписи {@code s = r·d + k·e} (хэш, прочитанный младшим байтом
 * вперёд, по модулю порядка кривой, нуль заменяется единицей). Запрещён детерминированный нонс,
 * выведенный из байт хэша в обход {@code e}: у двух хэшей с разными {@code e} он может совпасть.
 * Запрещён и нонс, не зависящий от кривой: один закрытый ключ на двух кривых одной длины при
 * равном {@code e} дал бы общий нонс (реализация библиотеки добавляет в затравку идентификатор
 * кривой). Случайный нонс допустим, если он взят из криптостойкого источника.
 *
 * <h3>Доступ к подписанту</h3>
 * {@link #signHash(byte[])} подписывает любой хэш, который ему передали, то есть служит
 * оракулом подписи. Его нельзя отдавать недоверенной стороне без авторизации и проверки того,
 * что именно подписывается.
 *
 * <h3>Контракт исключений</h3>
 * Исключения при подписи (HSM недоступен, таймаут, извлечённая смарт-карта) пропагируются
 * как unchecked без обёртки — консистентно с прямым вызовом закрытого ключа.
 *
 * <h3>Потокобезопасность</h3>
 * Библиотека не сериализует вызовы к {@code GostSigner}. Реализация сама отвечает за
 * потокобезопасность (PKCS#11-сессии часто не потокобезопасны без явной синхронизации).
 */
public interface GostSigner {

    /**
     * Подписывает готовый хэш закрытым ключом ГОСТ Р 34.10-2012.
     *
     * @param hash готовый хэш (длина должна быть равна hlen кривой {@link #getParams()})
     * @return подпись в X.509-формате {@code s ∥ r} big-endian (64 или 128 байт)
     */
    byte[] signHash(byte[] hash);

    /**
     * Параметры кривой подписанта.
     * <p>Билдеры используют их для выбора длины хэша (hlen) при хэшировании TBS
     * и для построения AlgorithmIdentifier подписи.
     */
    ECParameters getParams();

    /**
     * Открытый ключ, соответствующий закрытому ключу подписанта.
     *
     * <p>Используется билдерами для self-verify: сразу после сборки подпись проверяется
     * этим ключом (fail-closed) — ловит неисправный HSM-адаптер, вернувший подпись не тем
     * ключом, который заявлен (например, при неверно сконфигурированном слоте/алиасе).
     *
     * <p><b>Граница гарантии:</b> self-verify подтверждает лишь внутреннюю самосогласованность
     * подписанта — «подписано тем ключом, который подписант декларирует своим». Он <b>не</b>
     * гарантирует, что это правильный ключ издателя: подключение адаптера к резервному или
     * чужому слоту библиотека обнаружить не может — это знание принадлежит оператору.
     *
     * <p>Открытый ключ не секретен и может кэшироваться.
     */
    PublicKeyParameters getPublicKey();

    /**
     * Дефолтная реализация поверх закрытого ключа в памяти JVM.
     *
     * <p>Открытый ключ выводится немедленно (Q = d·G) в момент вызова — пока ключ гарантированно
     * жив. Это снимает неоднозначность тайминга {@link PrivateKeyParameters#destroy()}: после
     * уничтожения ключа {@link #signHash(byte[])} перестанет работать, а {@link #getPublicKey()}
     * продолжит возвращать корректный кэшированный открытый ключ.
     *
     * <p>Владение закрытым ключом остаётся за вызывающим: реализация не вызывает
     * {@code priv.destroy()} — уничтожайте ключ явно после завершения работы.
     *
     * @param priv закрытый ключ; не может быть {@code null}
     * @throws IllegalArgumentException если {@code priv} равен {@code null}
     */
    static GostSigner of(PrivateKeyParameters priv) {
        return of(priv, NonceMode.DEFAULT);
    }

    /**
     * Дефолтная реализация поверх закрытого ключа в памяти JVM с явно заданным режимом нонса,
     * см. {@link #of(PrivateKeyParameters)} и {@link NonceMode}.
     *
     * @param priv закрытый ключ; не может быть {@code null}
     * @param mode режим нонса; не может быть {@code null}
     * @throws IllegalArgumentException если {@code priv} или {@code mode} равен {@code null}
     */
    static GostSigner of(PrivateKeyParameters priv, NonceMode mode) {
        return new PrivateKeySigner(priv, mode);
    }
}
