package org.rssys.gost.signature;

/**
 * Источник случайной добавки {@code Z} для гибридного режима ({@link NonceMode#HEDGED}).
 *
 * <p>Только внутри пакета: публичного входа «передать байты {@code Z}» нет намеренно, снаружи
 * источник задаётся {@link java.security.SecureRandom}. Массив принадлежит подписанту: он
 * создаёт его, источник заполняет, подписант затирает.
 */
interface NoiseSource {

    /** Заполняет массив случайными байтами целиком. */
    void fill(byte[] out);
}
