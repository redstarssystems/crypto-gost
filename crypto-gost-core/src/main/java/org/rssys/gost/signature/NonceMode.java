package org.rssys.gost.signature;

/**
 * Способ выработки нонса {@code k} при подписи ГОСТ Р 34.10-2012.
 *
 * <p>Оба режима выводят {@code k} через HMAC-DRBG на Стрибоге из закрытого ключа {@code d},
 * числа {@code e} из уравнения подписи и идентификатора кривой. Различие одно: гибридный режим
 * дополнительно подмешивает свежие случайные байты {@code Z}.
 *
 * <p>RFC 7091 §6.1 допускает и случайный, и псевдослучайный {@code k}, поэтому оба режима
 * соответствуют стандарту.
 */
public enum NonceMode {

    /**
     * Гибридный режим по образцу черновика draft-irtf-cfrg-det-sigs-with-noise-05 (истёк, RFC
     * не стал): во вход HMAC-DRBG добавлены {@code Z} длиной {@code rolen} байт, один и тот же
     * на шагах d и f, и нули до границы блока хэш-функции.
     *
     * <p>Защищает от атаки сбоем по разности двух подписей одного сообщения и от усреднения
     * тайминга по одному {@code k}; не закрывает одиночный сбойный нонс и сбой в вычислении
     * {@code k·G}. Подпись одного хэша каждый раз другая. Если источник случайности повторяет
     * или предсказуем, подпись не хуже детерминированной: {@code d} и {@code e} остаются во
     * входе, поэтому даже известный противнику {@code Z} {@code k} не раскрывает. Исключение
     * источника случайности означает отказ подписи без отката на детерминизм; слабый источник
     * исключения не даёт и обнаруживаться не будет.
     */
    HEDGED,

    /**
     * Детерминированный режим: {@code k} зависит только от {@code (d, e, кривая)}, подпись
     * одного хэша тем же ключом всегда одна и та же. Менее безопасен: сбойная и верная подписи
     * одного сообщения имеют общий {@code k}, и {@code d} вычисляется из разности {@code s}.
     * Нужен для воспроизводимости (эталоны, отладка). Источник случайности не вызывается.
     */
    DETERMINISTIC;

    /**
     * Режим по умолчанию для всех путей, где режим не задан явно ({@code ECDSASigner} без
     * режима, {@code Signature.sign}, {@code Signature.signHash}, {@code GostSigner.of}, JCA,
     * TLS, pkix): гибридный, {@link #HEDGED}. Подпись одного хэша каждый раз другая, и
     * воспроизводимость даёт только явный {@link #DETERMINISTIC}. Ранее выданные подписи
     * остаются верными: проверка от нонса не зависит. Раньше умолчание было детерминированным;
     * чтобы поведение не зависело от умолчания, задавайте режим явно.
     */
    public static final NonceMode DEFAULT = HEDGED;
}
