package org.rssys.gost.jsse.crl;

/**
 * Политика проверки CRL (Certificate Revocation List, RFC 5280 §5).
 * <p>
 * Определяет, требуется ли CRL и как реагировать на отсутствие CRLDistributionPoints.
 */
public enum CrlPolicy {

    /** CRL не проверять */
    DISABLED,

    /**
     * Проверить CRL если у сертификата есть CDP; нет CDP — OK.
     * <p>
     * Недоступные адреса CDP (сеть, таймаут, битый HTTP-ответ, неподходящий CRL) проверку отзыва
     * пропускают. Слишком большой CRL (больше предела загрузчика или {@code maxCrlSize}) не
     * считается недоступным адресом: это отказ проверки.
     */
    IF_CDP_PRESENT,

    /**
     * CRL обязателен для сертификата без OCSP-ответа: нет CDP, нет fetcher или все зеркала
     * недоступны - отказ.
     * <p>
     * При наличии OCSP-ответа (присланного или полученного по сети) CRL не проверяется.
     * Валидность OCSP проверяется отдельно; при её ошибке - отказ, повторной проверки по CRL нет.
     */
    REQUIRE
}
