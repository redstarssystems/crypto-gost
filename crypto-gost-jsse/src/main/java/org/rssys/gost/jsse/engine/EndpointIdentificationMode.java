package org.rssys.gost.jsse.engine;

/**
 * Режим проверки имени узла (RFC 6125) для клиентских engine одного контекста сессий.
 * <p>
 * Режим действует на уровне контекста: уже созданные engine не меняются, а чтобы вернуть
 * проверку после {@link #DISABLED}, нужно создать новый контекст.
 */
public enum EndpointIdentificationMode {

    /**
     * Поведение JSSE по умолчанию: HTTPS включается, когда у engine известен узел. Без узла
     * проверять нечего, рукопожатие идёт без проверки имени (с предупреждением в журнале).
     * {@code null} в {@code SSLParameters.setEndpointIdentificationAlgorithm} отключает проверку.
     */
    DEFAULT,

    /**
     * Строгий режим для интеграций, которые не задают проверку имени сами (Netty): HTTPS
     * включён всегда, узел обязателен, а {@code null} в {@code SSLParameters} считается «не
     * задано» и текущее значение не меняет. Клиентский engine без узла отказывает на
     * {@code beginHandshake()} до отправки ClientHello. Явно отключить проверку у конкретного
     * engine можно пустой строкой в {@code setSSLParameters}.
     */
    STRICT,

    /**
     * Проверка имени отключена осознанно: клиентские engine создаются без HTTPS. Небезопасно:
     * сертификат любого доверенного УЦ принимается для любого узла.
     */
    DISABLED
}
