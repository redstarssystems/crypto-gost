package org.rssys.gost.pkix.cert;

/**
 * Политика проверки срока действия доверенного якоря-сертификата.
 *
 * <p>RFC 5280 §6.1 не включает срок trust anchor в проверку пути, поэтому перевыпущенный
 * корень с тем же ключом остаётся точкой доверия, даже если сам сертификат уже истёк. Строгие
 * потребители (например, подпись CMS, где срок якоря важен для долговременной проверки)
 * вправе требовать обратного. Политика задаётся вместе с набором якорей
 * ({@link TrustAnchors#withExpiryPolicy}), а не потребителем в отдельной проверке.</p>
 *
 * <p>Закреплённый конечный сертификат (цепочка из одного сертификата) проверяется на срок как
 * обычный leaf при любой политике.</p>
 */
public enum AnchorExpiryPolicy {

    /**
     * Политика не задана: решает потребитель. Общая проверка цепочки ({@code ChainValidator}) и
     * TLS трактуют значение как {@link #WARN}, CMS и CAdES - как {@link #REJECT}.
     */
    DEFAULT,

    /** Истёкший якорь при цепочке из нескольких сертификатов допускается, в журнал пишется WARNING. */
    WARN,

    /** Истёкший якорь отклоняется ({@code PkixException.Reason.EXPIRED}). */
    REJECT
}
