package org.rssys.gost.pkix.cert;

/**
 * Политика свежести данных отзыва для проверки CAdES-X Long.
 *
 * <p>Политика влияет только на нижнюю границу окна выпуска доказательства.
 * Верхняя граница задаётся временем {@code escTimeStamp} и обязательна в обеих
 * политиках: доказательство не может быть выпущено позже, чем C-ссылки были
 * защищены меткой времени.</p>
 */
public enum RevocationFreshnessPolicy {

    /**
     * Строгая политика: доказательство должно быть выпущено не раньше момента
     * подписи (с допуском расхождения часов). Это закрывает подмену старым
     * {@code good}-доказательством, выпущенным до подписи.
     */
    STRICT,

    /**
     * Политика ETSI по умолчанию: доказательство должно быть свежим на момент
     * сбора ({@code escTimeStamp}), но может быть выпущено до подписи.
     *
     * <p>Не защищает от подмены старым {@code good}-доказательством, которое
     * ещё не вышло из {@code nextUpdate} на момент подписи.</p>
     */
    ETSI_DEFAULT
}
