package org.rssys.gost.pkix.cms;

/**
 * Какие подписанты SignedData обязаны пройти проверку.
 *
 * <p>Выбор обязателен при создании {@link VerifyOptions}: от него зависит гарантия, которую
 * получает вызывающий, поэтому умолчания нет.</p>
 */
public enum SignerSelection {

    /**
     * Достаточно одного валидного подписанта. Проверка идёт по порядку; подписант с битой подписью,
     * недоверенной цепочкой или отзывом пропускается, результат содержит первого прошедшего.
     * Остальные подписанты до конца не проверяются.
     */
    ANY,

    /** Каждый подписант обязан пройти; любой отказ немедленно прерывает проверку. */
    ALL
}
