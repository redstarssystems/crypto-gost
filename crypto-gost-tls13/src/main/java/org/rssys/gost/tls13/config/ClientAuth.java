package org.rssys.gost.tls13.config;

/**
 * Режим аутентификации клиента сервером TLS 1.3 (mTLS, RFC 8446 §4.3.2, §4.4.2).
 * <p>
 * Режим задаётся вместе с доверенными якорями методами
 * {@link TlsServerConfig#needClientAuth} и {@link TlsServerConfig#wantClientAuth}, поэтому
 * состояние «режим без якорей» или «якоря без режима» невозможно.
 */
public enum ClientAuth {

    /** Сертификат клиента не запрашивается (по умолчанию). */
    NONE,

    /**
     * Сертификат запрашивается, но клиент вправе не предъявлять его. Предъявленный сертификат
     * проверяется в полном объёме и при ошибке приводит к отказу. Приложение обязано само
     * проверить, что клиент аутентифицирован ({@code TlsSession.hasPeerCertificate()}).
     */
    WANT,

    /** Сертификат запрашивается и обязателен: клиент без него получает {@code certificate_required}. */
    NEED
}
