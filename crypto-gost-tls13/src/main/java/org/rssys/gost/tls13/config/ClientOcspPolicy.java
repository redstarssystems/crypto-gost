package org.rssys.gost.tls13.config;

/**
 * Политика сервера в отношении OCSP-staple клиентского сертификата при mTLS
 * (RFC 8446 §4.4.2.1).
 * <p>
 * Действует только при включённой аутентификации клиента (заданы доверенные якоря).
 * Присланный staple проверяется всегда: невалидный, просроченный или относящийся к другому
 * сертификату staple приводит к отказу ({@code bad_certificate}) в режимах {@link #REQUEST}
 * и {@link #REQUIRE}.
 */
public enum ClientOcspPolicy {

    /**
     * Staple не запрашивается (по умолчанию). Присланный клиентом staple отвергается как
     * незапрошенное расширение ({@code unsupported_extension}, RFC 8446 §4.2).
     */
    OFF,

    /**
     * Сервер запрашивает staple расширением {@code status_request} в CertificateRequest.
     * Если клиент приложил ответ - он проверяется; отсутствие ответа допустимо.
     */
    REQUEST,

    /**
     * Сервер запрашивает staple и требует его: клиент без staple получает отказ
     * ({@code bad_certificate}) на этапе проверки сертификата.
     */
    REQUIRE
}
