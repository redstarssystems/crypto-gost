package org.rssys.gost.tls13.psk;

import java.util.Locale;
import java.util.Objects;
import org.rssys.gost.tls13.TlsConstants;

/**
 * Привязка клиентского PSK-тикета к серверу и модели доверия, по которой сервер был
 * принят в исходном рукопожатии (RFC 8446 §4.2.11, §4.6.1).
 *
 * <p>Возобновление по PSK не показывает сертификат сервера и не проверяет его заново: оно
 * наследует результат проверки исходной сессии. Поэтому тикет разрешено предъявлять только
 * тому же серверу и только при той же модели доверия. Иначе тикет, полученный от сервера A,
 * завершил бы рукопожатие с сервером B без проверки цепочки, имени и отзыва.</p>
 *
 * <p>Привязка сравнивается по равенству обоих полей. Строгое равенство {@code serverName}
 * строже RFC (достаточно, чтобы новое имя было допустимо для сертификата исходной сессии):
 * тикет для {@code example.com} не будет предъявлен {@code www.example.com}, даже если
 * сертификат покрывает оба имени. Это безопасный выбор. В режиме без сверки имени с
 * сертификатом ({@code withoutHostnameVerification()}) допустимость имени для сертификата
 * исходной сессии не проверялась: пользователь сам отказался от этой проверки.</p>
 *
 * <p>Привязку вычисляет и сверяет TLS-стек. {@link PskStore} только хранит её в
 * {@link PskEntry} и фильтрует записи по равенству; стек перепроверяет результат, не
 * полагаясь на честность хранилища.</p>
 *
 * @param serverName     имя сервера, отправленное в SNI (в нижнем регистре), или {@code null},
 *                       если имя не задано
 * @param verificationId идентификатор модели доверия (hex отпечатка): режим проверки сервера,
 *                       якоря, политика отзыва и совместимости, хэш KDF набора шифров;
 *                       константа у серверных записей ({@link #forServer(String)})
 */
public record PskBinding(String serverName, String verificationId) {

    /**
     * Привязка серверной записи: тикет принадлежит соединению с этим именем SNI клиента.
     *
     * <p>RFC 6066 §3: сервер MUST NOT принимать возобновление, если {@code server_name}
     * содержит другое имя, и должен перейти к полному рукопожатию. RFC 8446 §4.2.11 серверной
     * привязки не требует, но она защищает общее хранилище нескольких арендаторов: тикет
     * арендатора A не принимается при SNI арендатора B. Отсутствие SNI совпадает только с
     * отсутствием SNI.</p>
     *
     * @param sni имя из расширения {@code server_name} клиента или {@code null}
     * @return привязка серверной записи
     */
    public static PskBinding forServer(String sni) {
        return new PskBinding(
                sni == null || sni.isBlank() ? null : sni, TlsConstants.PSK_BINDING_SERVER_ID);
    }

    /**
     * Нормализует имя к нижнему регистру: DNS-имена регистронезависимы, а инвариант должен
     * держать сам тип, иначе привязка, созданная другим кодом, никогда не совпала бы с
     * вычисленной стеком и возобновление молча отключилось бы.
     */
    public PskBinding {
        Objects.requireNonNull(verificationId, "verificationId");
        serverName = serverName == null ? null : serverName.toLowerCase(Locale.ROOT);
    }
}
