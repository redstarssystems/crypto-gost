package org.rssys.gost.tls13.psk;

/**
 * Хранилище PSK для session resumption (RFC 8446 §2.2).
 *
 * <p><b>Контракт массива-ключа.</b> Реализация НЕ ДОЛЖНА сохранять ссылку на массив
 * {@code ticket}, переданный в {@link #get(byte[])}, {@link #peek(byte[])} и
 * {@link #remove(byte[])}: TLS-стек затирает этот массив сразу после возврата, чтобы тикет не жил
 * в куче дольше нужного. Удерживаемая ссылка обнулилась бы вместе с ним, и запись перестала бы
 * находиться. Нужно скопировать байты или вычислить от них ключ. Это касается и хранилищ во
 * внешних системах (Redis, база данных).
 *
 * <p><b>Конкурентный доступ.</b> {@link #peek(byte[])} и {@link #get(byte[])} не образуют
 * атомарной пары: пока одно соединение проверяет запись, другое с тем же тикетом может её
 * забрать. Запись, возвращённая {@code peek}, может оказаться уже затёртой, и её
 * {@link PskEntry#getPsk()} вернёт null; сервер считает такую identity неизвестной.
 *
 * <p>Разделение ответственности:
 * <ul>
 *   <li><b>Read API</b> — для пользовательского кода (get, getForResumption, remove, size, evictExpired)</li>
 *   <li><b>TLS callback</b> — {@link #onTicketReceived(PskEntry)} вызывается стеком, не пользователем</li>
 * </ul>
 *
 * <p>0-RTT и external PSK не поддерживаются.
 *
 * <p>Возобновление по PSK не проверяет сертификат сервера и его отзыв заново: оно наследует
 * проверку исходной сессии, поэтому предел действия такой проверки — срок жизни тикета.
 *
 * <p><b>Клиентское</b> хранилище может держать тикеты многих серверов: каждая запись несёт
 * {@link PskBinding}, а {@link #getForResumption(PskBinding)} возвращает только запись с
 * равной привязкой. <b>Серверное</b> хранилище ищет тикет только по его байтам, без привязки,
 * поэтому используйте один экземпляр на одну идентичность сервера: не делите его между
 * серверами или SNI-арендаторами с разными политиками и ключами.
 *
 * <p>Клиентское и серверное хранилища должны быть разными экземплярами: запись клиента и
 * запись сервера с одним и тем же тикетом в общем хранилище затирают друг друга.
 */
public interface PskStore {

    // ========================================================================
    // Read API — для пользовательского кода
    // ========================================================================

    /**
     * Извлекает запись и удаляет её из хранилища (одноразовость тикета, RFC 8446 §8.1).
     * Ссылку на {@code ticket} не сохранять (см. контракт массива-ключа выше).
     *
     * @param ticket идентификатор тикета
     * @return запись по идентификатору тикета, или null если нет/expired
     */
    PskEntry get(byte[] ticket);

    /**
     * @param binding привязка, которую клиент ожидает от записи (не null)
     * @return валидный кандидат для resumption attempt с равной привязкой, или null если нет.
     *          MUST не возвращать expired (expiry check per-call) и записи с другой привязкой.
     */
    PskEntry getForResumption(PskBinding binding);

    /**
     * Удаляет тикет (single-use: RFC 8446 §8.1). Ссылку на {@code ticket} не сохранять
     * (см. контракт массива-ключа выше).
     *
     * @param ticket идентификатор тикета
     */
    void remove(byte[] ticket);

    /**
     * Ищет запись без удаления. Ссылку на {@code ticket} не сохранять (см. контракт
     * массива-ключа выше).
     *
     * @param ticket идентификатор тикета
     * @return запись по идентификатору тикета без удаления, или null если нет/expired
     */
    PskEntry peek(byte[] ticket);

    /** @return количество сохранённых тикетов */
    int size();

    /** Удаляет все просроченные PSK-тикеты. */
    void evictExpired();

    /** Удаляет все PSK-тикеты (с зачисткой ключевого материала).
     *  <p>Используется в JMH-бенчмарках для сброса состояния между итерациями. */
    void clear();

    // ========================================================================
    // TLS callback — вызывается стеком, не пользователем
    // ========================================================================

    /** Вызывается TLS-стеком при получении NewSessionTicket от пира.
     *  Не вызывать напрямую из пользовательского кода.
     *  Implementation может бросить RuntimeException при ошибке backend;
     *  TLS-стек логирует и продолжает handshake. */
    void onTicketReceived(PskEntry entry);
}
